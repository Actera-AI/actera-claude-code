// Reproduce notices from the exact dependency modules linked into all six bundles.
// Include nested upstream license and attribution files as well as root licenses.
import assert from 'node:assert/strict'
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gunzipSync } from 'node:zlib'

const root = fileURLToPath(new URL('../', import.meta.url))
const vendor = resolve(root, 'plugins/actera/vendor/gitleaks')
const manifest = JSON.parse(await readFile(resolve(vendor, 'manifest.json'), 'utf8'))
const env = { ...process.env, GOWORK: 'off' }
const go = args => execFileSync('go', args, { cwd: resolve(root, 'scanner'), env, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 }).trim()
assert.equal(go(['version']).split(' ')[2], manifest.goVersion.split(' ')[2], 'Use the Go toolchain recorded in the scanner manifest')
const modules = new Map()
await mkdir(resolve(root, '.tools/notices'), { recursive: true })
for (const entry of Object.values(manifest.binaries)) {
  const binary = resolve(root, '.tools/notices', entry.file.replace('.gz', '.bin'))
  await writeFile(binary, gunzipSync(await readFile(resolve(vendor, entry.file))))
  for (const line of go(['version', '-m', binary]).split('\n')) {
    const fields = line.trim().split(/\s+/)
    if (fields[0] === 'dep') modules.set(fields[1], fields[2])
  }
}

async function licenses(directory, prefix = '') {
  const files = []
  for (const entry of await readdir(resolve(directory, prefix), { withFileTypes: true })) {
    if (entry.name === '.git') continue
    const name = prefix + entry.name
    if (entry.isDirectory()) files.push(...await licenses(directory, name + '/'))
    else if (/^(LICENSE|LICENCE|COPYING|NOTICE|AUTHORS|PATENTS)(?:[._-].*)?$/i.test(entry.name)) files.push(name)
  }
  return files.sort()
}
assert.ok(modules.size > 0, 'No linked modules found in scanner bundles')
const sections = ['Third-party software in the Actera scanner\nGenerated by scripts/scanner-notices.mjs from the bundled binaries and pinned module sources.\nUpstream license and attribution files are reproduced below, including nested notices.\n']
const goroot = go(['env', 'GOROOT'])
sections.push(`=== Go (${manifest.goVersion}) / LICENSE ===\n\n${await readFile(resolve(goroot, 'LICENSE'), 'utf8')}`)
for (const [module, version] of [...modules].sort(([a], [b]) => a.localeCompare(b, 'en'))) {
  const info = JSON.parse(go(['mod', 'download', '-json', `${module}@${version}`]))
  const files = await licenses(info.Dir)
  assert.ok(files.some(name => /(?:^|\/)(LICENSE|LICENCE|COPYING)/i.test(name)), `No license found for ${module}`)
  for (const file of files) sections.push(`=== ${module}@${version} / ${file} ===\n\n${await readFile(resolve(info.Dir, file), 'utf8')}`)
}
const output = sections.join('\n').replaceAll('\r\n', '\n').replace(/[ \t]+$/gm, '').trimEnd() + '\n'
const target = resolve(vendor, 'THIRD_PARTY_NOTICES.txt')
if (process.argv.includes('--check')) assert.equal(await readFile(target, 'utf8'), output, 'Scanner notices changed; run node scripts/scanner-notices.mjs')
else await writeFile(target, output)
console.log(`Scanner notices verified for Go and ${modules.size} linked modules`)
